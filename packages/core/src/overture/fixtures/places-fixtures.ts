const MARGIN = 0.01;

/**
 * Synthetic division areas (labelled as such in their names' ids) reproducing `expectedAdmin`:
 * each LGA is the rectangle around its fixture points plus a small margin, each state the
 * rectangle around its LGAs. `extra` adds test areas (for example a wider Ikeja for synthetic
 * sample places).
 */
export function overtureFixtureDivisions(
  extra: Array<{
    state: string;
    lga: string;
    minX: number;
    minY: number;
    maxX: number;
    maxY: number;
  }> = [],
): OvertureDivision[] {
  const lgas = new Map<
    string,
    { state: string; lga: string; minX: number; minY: number; maxX: number; maxY: number }
  >();
  for (const r of RECORDS) {
    if (!r.expectedAdmin.lga || r.place.lon === null || r.place.lat === null) continue;
    const key = `${r.expectedAdmin.state}|${r.expectedAdmin.lga}`;
    const b = lgas.get(key) ?? {
      state: r.expectedAdmin.state,
      lga: r.expectedAdmin.lga,
      minX: Infinity,
      minY: Infinity,
      maxX: -Infinity,
      maxY: -Infinity,
    };
    b.minX = Math.min(b.minX, r.place.lon - MARGIN);
    b.minY = Math.min(b.minY, r.place.lat - MARGIN);
    b.maxX = Math.max(b.maxX, r.place.lon + MARGIN);
    b.maxY = Math.max(b.maxY, r.place.lat + MARGIN);
    lgas.set(key, b);
  }
  for (const e of extra) lgas.set(`${e.state}|${e.lga}`, { ...e });
  const states = new Map<string, { minX: number; minY: number; maxX: number; maxY: number }>();
  for (const b of lgas.values()) {
    const s = states.get(b.state) ?? {
      minX: Infinity,
      minY: Infinity,
      maxX: -Infinity,
      maxY: -Infinity,
    };
    states.set(b.state, {
      minX: Math.min(s.minX, b.minX),
      minY: Math.min(s.minY, b.minY),
      maxX: Math.max(s.maxX, b.maxX),
      maxY: Math.max(s.maxY, b.maxY),
    });
  }
  const out: OvertureDivision[] = [];
  let n = 0;
  for (const [state, b] of states) {
    n += 1;
    out.push({
      id: `synthetic-region-${n}`,
      divisionId: `synthetic-division-region-${n}`,
      subtype: "region",
      name: state,
      region: NIGERIAN_STATE_CODES[state] ?? null,
      country: "NG",
      wkb: rectangleWkb(b.minX, b.minY, b.maxX, b.maxY),
    });
  }
  for (const b of lgas.values()) {
    n += 1;
    out.push({
      id: `synthetic-county-${n}`,
      divisionId: `synthetic-division-county-${n}`,
      subtype: "county",
      name: b.lga,
      region: NIGERIAN_STATE_CODES[b.state] ?? null,
      country: "NG",
      wkb: rectangleWkb(b.minX, b.minY, b.maxX, b.maxY),
    });
  }
  return out;
}
